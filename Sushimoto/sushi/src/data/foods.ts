export function getFoodsByCategory(categorySlug: string): Food[] {
  return foods.filter(
    (food) => food.category === categorySlug
  );
}

export function getFoodBySlug(slug: string): Food | undefined {
  return foods.find((food) => food.slug === slug);
}

export function getChefRecommendations(): Food[] {
  return foods.filter((food) => food.isChefRecommendation);
}

export function getTodaySpecials(): Food[] {
  return foods.filter((food) => food.isTodaySpecial);
}

export function getFeaturedDishes(): Food[] {
  return foods.slice(0, 6);
}
